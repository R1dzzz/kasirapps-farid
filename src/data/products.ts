export function getProductBySlug(slug: string): Product | undefined {
  return products.find(p => p.slug === slug);
}

export function getProductsByCategory(categoryId: string): Product[] {
  return products.filter(p => p.category_id === categoryId);
}

export function getPopularProducts(limit: number = 8): Product[] {
  return [...products].sort((a, b) => b.sold_count - a.sold_count).slice(0, limit);
}

export function getLatestProducts(limit: number = 8): Product[] {
  return [...products].sort((a, b) => new Date(b.created_at).getTime() - new Date(a.created_at).getTime()).slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.slug.toLowerCase().includes(q)
  );
}

export function filterProducts(
  categoryId?: string,
  minPrice?: number,
  maxPrice?: number,
  sort?: 'newest' | 'price_asc' | 'price_desc' | 'rating' | 'popular'
): Product[] {
  let result = [...products];

  if (categoryId) {
    result = result.filter(p => p.category_id === categoryId);
  }

  if (minPrice !== undefined) {
    result = result.filter(p => p.price >= minPrice);
  }

  if (maxPrice !== undefined) {
    result = result.filter(p => p.price <= maxPrice);
  }

  switch (sort) {
    case 'price_asc':
      result.sort((a, b) => a.price - b.price);
      break;
    case 'price_desc':
      result.sort((a, b) => b.price - a.price);
      break;
    case 'rating':
      result.sort((a, b) => b.rating - a.rating);
      break;
    case 'popular':
      result.sort((a, b) => b.sold_count - a.sold_count);
      break;
    case 'newest':
    default:
      result.sort((a, b) => new Date(b.created_at).getTime() - new Date(a.created_at).getTime());
      break;
  }

  return result;
}
